        # ! only SUM for now!

        df_impacts = pd.concat([df_absb])
        df_impacts = pd.concat([df_absb,df_relb])
        # ? REG_imp | PROD_COMM | dk
        df_impacts = df_impacts.groupby(['REG_imp','PROD_COMM']).agg({'dk':'sum'}).reset_index()

        self.inv_exog = df_impacts.astype({'PROD_COMM':'int'})

        return True
    
