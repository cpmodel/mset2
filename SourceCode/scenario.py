    def carbon_tax_rate_loop(self, country:str=None):
        """Parallel loop function for generating tax matrices by country. Saves the tax rate
        matrices in file.

        Parameters
        ----------
        country : str
            country to generate carbon tax file for

        Returns
        -------
        bool
            Returns True if completed
        """
          
        # first retrieve the tax rate file from the class
        tax_rate = self.tax_rate

        # TODO REG_exp is ALL for now
        tax_rate['REG_exp'] = 'ALL'
        # tax_rate_country = tax_rate[tax_rate['REG_imp']==country].copy()

        # process flows_table, for simplicity the flows table (excel) allows flows to
        # be allocated to multiple sectors either in hyphen e.g. 10-30 or comma e.g.
        # 10,11,15 format, these are parsed to actual sectors here

        tax_rate = resolve_hyphen(tax_rate, 'PROD_COMM')
        tax_rate = resolve_comma(tax_rate, 'PROD_COMM')
        tax_rate = resolve_hyphen(tax_rate, 'TRAD_COMM')
        tax_rate = resolve_comma(tax_rate, 'TRAD_COMM')

        tax_rate = resolve_comma(tax_rate, 'REG_imp')

        # treatment of ALL in PROD_COMM, ie all upstream sectors impacted
        tax_rate = resolve_all(tax_rate, 'PROD_COMM', [x for x in np.arange(1,121)] + ['FD_1','FD_2','FD_3','FD_4','FD_5','FD_6'])
        tax_rate = resolve_all(tax_rate, 'TRAD_COMM', [x for x in np.arange(1,121)])
        tax_rate = resolve_all(tax_rate, 'REG_exp', self.REGIONS['Region_acronyms'].to_list())
        tax_rate = resolve_all(tax_rate, 'REG_imp', self.REGIONS['Region_acronyms'].to_list())
        
        tax_rate = tax_rate.groupby(['REG_exp','REG_imp','PROD_COMM','TRAD_COMM']).aggregate({'delta_tax':'sum'}).reset_index()

        tax_rate = tax_rate.rename(columns={'delta_tax':'ctax'})
        self.temp.save_to_pickle(tax_rate, "carbon_tax_rate".format(country))

        return tax_rate
    
